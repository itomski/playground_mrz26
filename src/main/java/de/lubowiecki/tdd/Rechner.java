package de.lubowiecki.tdd;

public class Rechner {

    double add(double a, double b) {
        return a + b;
    }

    double sub(double a, double b) {
        return a - b;
    }

    double div(double a, double b) {
        return a / b;
    }

    double multi(double a, double b) {
        return a * b;
    }
}
